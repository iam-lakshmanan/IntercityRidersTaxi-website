import assert from 'node:assert/strict';
const base = process.env.INTERCITY_TEST_URL || 'http://localhost:3011';
const form = { tripType: 'oneway', pickup: 'Coimbatore', drop: 'Chennai', pickupDate: '2099-01-10', pickupTime: '10:30', vehicle: 'sedan', customerName: 'Integration Test', mobile: '9876543210', email: '', womanAlone: false, seniorCitizen: false, travellingWithInfant: false, extraLuggage: false };
async function post(path, data) {
  const response = await fetch(`${base}${path}`, { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: base }, body: JSON.stringify(data) });
  return { status: response.status, data: await response.json() };
}
const quote = await post('/api/fare-estimation', { vehicleId: 'sedan', tripType: 'oneway', distanceKm: 200, durationMins: 240 });
assert.equal(quote.status, 200, JSON.stringify(quote.data));
assert.equal(quote.data.total, 3400);
console.log('PASS: fare calculation from Google route metrics');
const requestId = 'test-request-1234567890';
const enquiry = await post('/api/enquiry', { form, requestId, event: 'enquiry', website: '' });
assert.equal(enquiry.status, 200, JSON.stringify(enquiry.data));
assert.equal(enquiry.data.delivered, true);
console.log('PASS: initial Telegram enquiry delivery');
const confirmationBody = { form, requestId, event: 'booking-confirmed', route: { distanceKm: 200, durationMins: 240 }, website: '' };
const confirmed = await post('/api/enquiry', confirmationBody);
assert.equal(confirmed.status, 200, JSON.stringify(confirmed.data));
assert.equal(confirmed.data.delivered, true);
console.log('PASS: confirmed booking delivery with recalculated fare');
const duplicate = await post('/api/enquiry', confirmationBody);
assert.equal(duplicate.data.reference, confirmed.data.reference);
console.log('PASS: duplicate confirmation returns the same reference');
assert.equal((await post('/api/enquiry', { ...confirmationBody, route: { distanceKm: 0, durationMins: 0 } })).status, 400);
console.log('PASS: invalid route metrics are rejected');
assert.equal((await post('/api/contact', { name: 'Integration Test', mobile: '9876543210', email: '', message: 'Isolated contact form integration test.', requestId: 'test-contact-1234567890', website: '' })).status, 200);
assert.equal((await post('/api/contact', { name: 'Integration Test', mobile: 'bad', email: '', message: 'Invalid number test.', requestId: 'test-contact-1234567890' })).status, 400);
console.log('PASS: contact delivery and server validation');
console.log('All integration checks passed. Telegram was mocked.');
